"""
Regenerates sql/02_cohort_mortality/maternal_diagnoses_group_load_en.sql from
two CSV files in the same folder:

  - maternal_diagnoses_group_catalog.csv  (one row per GDG_Mxx group)
  - maternal_diagnoses_group_map.csv      (one row per ICD code -> group_code)

This is the "modifiable" half of the diagnostic-group pipeline: the actual
classification decisions live in these two CSVs (edit them directly, or
re-export from the reviewed Excel), not in hand-written SQL. Whenever the
expert panel's feedback changes a code's group -- or renames/merges/splits a
group -- update the CSV(s) and re-run this script to get a fresh, correct
.sql file. Nothing else in the pipeline needs to change: the propagation
script (maternal_diagnoses_group_assign_en.sql) reads the catalog/map tables
generically and does not hard-code any group names or counts.

Usage:
    python scripts/generate_maternal_diagnoses_group_sql.py

Emmanuel still runs the generated .sql himself against the live database
(per the project's standing rule that DB-touching steps are his to run) --
this script only produces the file, it does not connect to Postgres.
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SQL_DIR = os.path.join(HERE, '..', 'sql', '02_cohort_mortality')
CATALOG_CSV = os.path.join(SQL_DIR, 'maternal_diagnoses_group_catalog.csv')
MAP_CSV = os.path.join(SQL_DIR, 'maternal_diagnoses_group_map.csv')
OUT_SQL = os.path.join(SQL_DIR, 'maternal_diagnoses_group_load_en.sql')


def sql_str(value):
    """Single-quote and escape a string for a literal SQL VALUES row."""
    return "'" + str(value).replace("'", "''") + "'"


def sql_bool(value):
    return 'TRUE' if str(value).strip().lower() in ('true', '1', 't', 'yes') else 'FALSE'


def read_csv(path):
    with open(path, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def build_catalog_values(rows):
    lines = []
    for r in rows:
        lines.append(
            f"    ({sql_str(r['group_code'])}, {sql_str(r['group_label_en'])}, "
            f"{sql_str(r['group_label_es'])}, {sql_bool(r['is_obstetric'])}, "
            f"{sql_bool(r['include_in_model'])}, {int(r['display_order'])})"
        )
    return ',\n'.join(lines)


def build_map_values(rows):
    lines = []
    for r in rows:
        lines.append(
            f"    ({sql_str(r['icd_code'])}, {int(r['icd_version'])}, {sql_str(r['group_code'])})"
        )
    return ',\n'.join(lines)


def main():
    catalog_rows = read_csv(CATALOG_CSV)
    map_rows = read_csv(MAP_CSV)

    valid_codes = {r['group_code'] for r in catalog_rows} | {'diagnoses_excluded'}
    bad = [r for r in map_rows if r['group_code'] not in valid_codes]
    if bad:
        raise SystemExit(
            f"{len(bad)} map row(s) reference a group_code not in the catalog "
            f"(and not the 'diagnoses_excluded' sentinel), e.g. {bad[0]}"
        )

    sql = f"""-- ============================================================================
-- MATERNAL DIAGNOSES GROUP CATALOG + MAP -- GENERATED FILE, DO NOT HAND-EDIT
-- ============================================================================
-- Generated by scripts/generate_maternal_diagnoses_group_sql.py from:
--   sql/02_cohort_mortality/maternal_diagnoses_group_catalog.csv ({len(catalog_rows)} rows)
--   sql/02_cohort_mortality/maternal_diagnoses_group_map.csv ({len(map_rows)} rows)
--
-- To change a code's group (or add/rename/merge a group), edit those two
-- CSVs and re-run the generator script -- do not edit this file directly,
-- your changes will be overwritten next time it runs.
--
-- Run this BEFORE maternal_diagnoses_group_assign_en.sql, which reads these
-- two tables to populate mimiciv.cohort_maternal_diagnoses.diagnoses_group
-- and (once mimiciv.cohort_maternal_dataset exists) the gdg_m01..gdg_m28
-- boolean feature columns.
-- ============================================================================

DROP TABLE IF EXISTS mimiciv.maternal_diagnoses_group_map;
DROP TABLE IF EXISTS mimiciv.maternal_diagnoses_group_catalog;

CREATE TABLE mimiciv.maternal_diagnoses_group_catalog (
    group_code        varchar(20) PRIMARY KEY,
    group_label_en    varchar(200) NOT NULL,
    group_label_es    varchar(200) NOT NULL,
    is_obstetric      boolean NOT NULL,
    include_in_model  boolean NOT NULL DEFAULT TRUE,
    display_order     int NOT NULL
);

INSERT INTO mimiciv.maternal_diagnoses_group_catalog
    (group_code, group_label_en, group_label_es, is_obstetric, include_in_model, display_order)
VALUES
{build_catalog_values(catalog_rows)};

CREATE TABLE mimiciv.maternal_diagnoses_group_map (
    icd_code     varchar(10) NOT NULL,
    icd_version  int NOT NULL,
    group_code   varchar(20) NOT NULL,  -- one of the catalog's group_code values, or the
                                         -- 'diagnoses_excluded' sentinel (administrative /
                                         -- encounter codes with no expected mortality signal --
                                         -- see get_maternal_diagnoses_query() in database.py,
                                         -- which already filters on this exact sentinel value)
    PRIMARY KEY (icd_code, icd_version)
);

INSERT INTO mimiciv.maternal_diagnoses_group_map (icd_code, icd_version, group_code)
VALUES
{build_map_values(map_rows)};

-- Sanity check: every code in mimiciv.cohort_maternal_diagnoses should find
-- a match here once both tables exist. Run after maternal_diagnoses_group_assign_en.sql:
-- SELECT count(*) FROM mimiciv.cohort_maternal_diagnoses cmd
-- LEFT JOIN mimiciv.maternal_diagnoses_group_map m
--   ON cmd.icd_code = m.icd_code AND cmd.icd_version = m.icd_version
-- WHERE m.icd_code IS NULL;  -- expect 0
"""

    with open(OUT_SQL, 'w', encoding='utf-8') as f:
        f.write(sql)
    print(f"Wrote {OUT_SQL} ({len(catalog_rows)} catalog rows, {len(map_rows)} map rows)")


if __name__ == '__main__':
    main()
